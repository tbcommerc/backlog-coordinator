import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../css/ui/', import.meta.url);
const scope = ':is(#task-detail-overlay, #create-task-overlay)';
// This is a specificity adapter, not a second implementation of sizing.
// Keep at-rules intact so responsive rules cannot escape their media query.
function scoped(css, selected) {
  css = css.replaceAll('\r\n', '\n').replace(/\/\*[\s\S]*?\*\//g, '').replace(/@import[^;]+;/g, '');
  let result = '', offset = 0;
  while (offset < css.length) {
    const open = css.indexOf('{', offset);
    if (open < 0) break;
    let close = open + 1, depth = 1;
    for (; close < css.length && depth; close++) {
      if (css[close] === '{') depth++;
      if (css[close] === '}') depth--;
    }
    const selector = css.slice(offset, open).trim();
    const body = css.slice(open + 1, close - 1);
    if (selector.startsWith('@media')) {
      const nested = scoped(body, selected);
      if (nested) result += `${selector} {\n${nested}}\n`;
    } else if (selector.startsWith(':root ') && (!selected || selected.has(selector))) {
      result += `${selector.replaceAll(':root ', scope + ' ')} {${body}}\n`;
    }
    offset = close;
  }
  return result;
}
export function buildDialogBridges() {
  const core = readFileSync(new URL('core.css', root), 'utf8').replaceAll('\r\n', '\n');
  const skinSelectors = new Set([':root .btn', ':root .btn.btn-ghost', ':root .btn.btn-ghost:hover', ':root .badge', ':root select:not([multiple]):is(:not([size]), [size="0"], [size="1"])']);
  return '/* Generated by ui-catalog/build-dialog-bridges.mjs. Do not edit. */\n'
    + ['sizing.css', 'tables.css'].map(name => scoped(readFileSync(new URL(name, root), 'utf8'))).join('\n') + scoped(core, skinSelectors);
}
const output = new URL('dialog-bridges.css', root);
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== buildDialogBridges()) throw new Error('Stale dialog bridges');
} else if (process.argv[1]?.endsWith('build-dialog-bridges.mjs')) writeFileSync(output, buildDialogBridges());
