from typing import Protocol
from contracts.models import Answer, ToolResult


class DataPort(Protocol):
    async def activate(self, execution: str, lease: str) -> str: ...
    async def check(self, execution: str, grant: str) -> None: ...
    async def catalog(self, execution: str, grant: str) -> dict: ...
    async def tool(self, execution: str, grant: str, name: str, arguments: dict, call_id: str) -> ToolResult: ...
    async def verify(self, execution: str, grant: str, candidate: Answer, receipts: list[str]) -> dict: ...
    async def validate(self, owner: str, receipts: list[str], proof: str) -> None: ...
    async def revoke(self, execution: str, grant: str) -> None: ...
    async def purge(self, owner: str, receipts: list[str]) -> None: ...
    async def result(self, owner: str, result_id: str, cursor: int, proof: str) -> dict: ...


class RuntimePort(Protocol):
    async def prepare(self, context: dict, bridge, schema: dict) -> dict: ...
    async def submit(self, handle: dict, envelope: dict, dispatch_ref: str) -> str: ...
    async def observe(self, handle: dict, cursor: str | None) -> list[dict]: ...
    async def inspect(self, handle: dict) -> str: ...
    async def collect(self, handle: dict) -> Answer: ...
    async def cancel(self, handle: dict) -> None: ...
    async def dispose(self, handle: dict) -> None: ...
