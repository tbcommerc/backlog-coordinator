# Optional slot questions asked opportunistically (preferred, not blocking)
OPTIONAL_SLOTS = ["department", "module", "scenarios", "business_rules", "regulatory_flags", "dependencies", "risks"]


def question_for(slot: str, style: str) -> str:
    entry = QUESTIONS.get(slot, {})
    return entry.get(style) or entry.get("business", f"Уточните, пожалуйста: {SLOT_LABELS.get(slot, slot)}.")


def chips_for(slot: str) -> list[dict]:
    entry = QUESTIONS.get(slot, {})
    return entry.get("chips", [])


def skip_chip(slot: str) -> dict:
    return {"label": "Пропустить (открытый вопрос)", "value": "__skip__"}
